def render_markdown(doc: dict) -> str:
    scope = (
        f"This clause applies only to {doc['commodity']} shipments to {doc['country']} "
        f"carried by {doc['carrier']}."
    )
    return "\n".join([
        f"# {doc['title']}",
        "",
        f"Carrier: {doc['carrier']}",
        f"Country: {doc['country']}",
        f"Commodity class: {doc['commodity']}",
        "",
        f"## {doc['section']} {doc['heading']}",
        "",
        f"{doc['section']}.1 {scope}",
        "",
        f"{doc['section']}.2 {doc['rule']}",
        "",
        f"{doc['section']}.3 {doc['limit']}",
        "",
    ])


def gold_questions() -> list[dict]:
    questions = list(HAND_QUESTIONS)
    for index, doc in enumerate(GOLD_DOCS, start=len(questions) + 1):
        promise = None if doc["expects_human_review"] else doc["rule"]
        questions.append({
            "id": f"q{index:02d}",
            "question": doc["question"],
            "gold_document": doc["name"].removesuffix(".md"),
            "gold_phrase": doc["gold_phrase"],
            "expects_human_review": doc["expects_human_review"],
            "promise": promise,
        })
    return questions


def distractor_docs() -> list[dict]:
    carriers = ["DHL", "FedEx", "UPS"]
    countries = ["Germany", "France", "Spain", "Belgium", "Netherlands", "Brazil"]
    docs = []
    serial = 0
    while len(docs) < 30:
        for folder, slug, sentence in DISTRACTOR_TOPICS:
            if len(docs) >= 30:
                break
            carrier = carriers[serial % len(carriers)]
            country = countries[serial % len(countries)]
            commodity = ["general", "electronics", "cold_chain", "pharma", "food"][serial % 5]
            section = f"30.{serial + 1}"
            docs.append({
                "folder": folder,
                "name": f"distractor_{slug}_{serial + 1:02d}.md",
                "title": f"{carrier} {country} archive note {serial + 1}",
                "carrier": carrier,
                "country": country,
                "commodity": commodity,
                "section": section,
                "heading": "Archive scan",
                "rule": f"{sentence} Reference {serial + 1} names {carrier}.",
                "limit": "This archive note does not promise a delivery date, a refund, or a customs release.",
            })
            serial += 1
    return docs


